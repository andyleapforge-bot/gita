hindi_data = {}
for line in all_hindi_translations.strip().split('\n'):
    if ':' in line and not line.startswith('CHAPTER'):
        parts = line.split(':', 1)
        ref = parts[0].strip()
        text = parts[1].strip()
        
        if '.' in ref:
            ch, shlok = ref.split('.')
            try:
                hindi_data[(int(ch), int(shlok))] = text
            except:
                pass

print(f"Loaded {len(hindi_data)} Hindi translations")

with open('assets/json/shlok_data.json', 'r', encoding='utf-8') as f:
    data = json.load(f)

# Update shloks
updates = 0
for shlok in data[1:]:
    chapter = shlok.get('__1')
    shlok_num = shlok.get('__3')
    
    key = (chapter, shlok_num)
    if key in hindi_data:
        shlok['__8_hi'] = hindi_data[key]
        updates += 1

# Save
with open('assets/json/shlok_data.json', 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

print(f"✓ Updated {updates} shloks with comprehensive Hindi summaries")
